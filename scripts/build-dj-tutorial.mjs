import {createRequire} from 'node:module';
import {resolve,join,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const modules=resolve(process.env.ANIMATUS_MODULES_ROOT||join(root,'../Animatus/Modules'));
const tutorial=join(modules,'packages/tutorial');
const requireTutorial=createRequire(join(tutorial,'package.json'));
const requireTools=createRequire(join(modules,'scripts/package.json'));
const {build}=requireTools('esbuild');
await build({
 entryPoints:[join(root,'src/tutorial/dj-tutorial.jsx')],
 outfile:join(root,'public/dj-tutorial.js'),
 bundle:true,format:'esm',platform:'browser',target:'es2022',minify:true,
 define:{'process.env.NODE_ENV':'"production"'},
 alias:{
  'animatus-tutorial/frontend':join(tutorial,'src/frontend/Tutorial.tsx'),
  'react':dirname(requireTutorial.resolve('react/package.json')),
  'react-dom':dirname(requireTutorial.resolve('react-dom/package.json')),
 },
 banner:{js:'// Generated by scripts/build-dj-tutorial.mjs from the shared Animatus Tutorial component. Do not edit.'},
});
console.log('Shared Animatus tutorial bundled: public/dj-tutorial.js');
